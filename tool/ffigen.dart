import 'package:ffigen/ffigen.dart';

import 'dart:io';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(entryPoints: [root.resolve('src/qr_decoder.h')]),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = node.originalName == 'qr_decode';
        },
        macroConstant: (node) {
          node.isIncluded = const {
            'QR_DECODE_NOT_FOUND',
            'QR_DECODE_INVALID_INPUT',
            'QR_DECODE_CAPACITY_EXCEEDED',
            'QR_DECODE_PANIC',
          }.contains(node.originalName);
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/qr_decoder.g.dart')),
      format: true,
      style: const NativeExternalBindings(),
      preamble: '// Generated by package:ffigen. Do not edit manually.\n',
    ),
  ).generate();
}
